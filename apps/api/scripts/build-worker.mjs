/**
 * Bundle the API for Cloudflare Workers into dist-worker/.
 * - node:sqlite -> Durable Object SQLite shim, node:fs -> bundled read-only files.
 * - import.meta.url becomes a stable per-file URL so relative asset paths still resolve
 *   against the bundled files (and box paths never end up in the bundle).
 * - migrations/*.sql and the listed assets are generated into src/worker/*.generated.ts.
 */
import { build } from 'esbuild';
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Write only on change so `wrangler dev` (watching src/) does not rebuild forever.
function writeIfChanged(file, text) {
  try { if (readFileSync(file, 'utf8') === text) return; } catch {}
  writeFileSync(file, text);
}

const api = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(api, '../..');
const out = join(api, 'dist-worker');
const vroot = '/td';

const assets = [
  'split/results.html', 'split/results.js', 'split/results.css', 'split/results-demo.json',
  'split/map.js', 'split/map.css',
  'apps/api/src/runner/recordings/derived.json', 'apps/api/src/runner/recordings/tokyo-tour.json',
  'apps/web/public/case-studies.json',
];
const files = {};
for (const rel of assets) files[`${vroot}/${rel}`] = readFileSync(join(root, rel), 'utf8');
writeIfChanged(join(api, 'src/worker/vfs.generated.ts'),
  `// Generated by scripts/build-worker.mjs. Do not edit.\nexport const files: Record<string, string> = ${JSON.stringify(files)};\n`);

const migrationsDir = join(api, 'migrations');
const migrations = readdirSync(migrationsDir).filter((n) => n.endsWith('.sql')).sort()
  .map((n) => [n, readFileSync(join(migrationsDir, n), 'utf8').replace(/^--.*$/gm, '')]);
writeIfChanged(join(api, 'src/worker/migrations.generated.ts'),
  `// Generated by scripts/build-worker.mjs. Do not edit.\nexport const MIGRATIONS: Array<[string, string]> = ${JSON.stringify(migrations)};\n`);

mkdirSync(out, { recursive: true });
copyFileSync(join(root, 'packages/engine-wasm/pkg/web/tastedraft_engine_bg.wasm'), join(out, 'tastedraft_engine_bg.wasm'));

const workerPlugin = {
  name: 'tastedraft-worker',
  setup(b) {
    b.onResolve({ filter: /^node:sqlite$/ }, () => ({ path: join(api, 'src/worker/sqlite-shim.ts') }));
    b.onResolve({ filter: /^(node:)?fs$/ }, () => ({ path: join(api, 'src/worker/fs-shim.ts') }));
    b.onResolve({ filter: /\.wasm$/ }, () => ({ path: './tastedraft_engine_bg.wasm', external: true }));
    b.onLoad({ filter: /\.(ts|js|mjs)$/ }, (args) => {
      if (args.path.includes('node_modules')) return undefined;
      const text = readFileSync(args.path, 'utf8');
      if (!text.includes('import.meta.url')) return undefined;
      const url = JSON.stringify(`file://${vroot}/${relative(root, args.path).replace(/\\/g, '/')}`);
      return { contents: text.replaceAll('import.meta.url', url), loader: args.path.endsWith('.ts') ? 'ts' : 'js' };
    });
  },
};

await build({
  entryPoints: [join(api, 'src/worker/index.ts')],
  outfile: join(out, 'index.js'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  conditions: ['workerd', 'worker', 'import', 'default'],
  external: ['cloudflare:*', 'node:*'],
  plugins: [workerPlugin],
  logLevel: 'warning',
});
console.log('Built', relative(root, join(out, 'index.js')));
